import fs from 'node:fs/promises';
import path from 'node:path';

const BENCHMARK_EXPRESSION_COUNT = 1000;
const BENCHMARK_TERMS_PER_EXPRESSION = 32;

const outputPath = path.join(
  process.cwd(),
  'app',
  'rsx-generated',
  'static-benchmark-expressions.generated.ts',
);

function buildExpressionString(expressionIndex) {
  const terms = [];
  for (
    let termIndex = 0;
    termIndex < BENCHMARK_TERMS_PER_EXPRESSION;
    termIndex += 1
  ) {
    terms.push(`v_${expressionIndex}_${termIndex}`);
  }
  return terms.join(' + ');
}

async function run() {
  const lines = [];
  lines.push('// @ts-nocheck');
  lines.push(
    '/* This file is auto-generated by scripts/generate-static-benchmark-expressions.mjs. Do not edit manually. */',
  );
  lines.push('');
  lines.push(
    "import { type IExpression, rsx } from '@rs-x/expression-parser';",
  );
  lines.push('');
  lines.push('export const benchmarkModel: Record<string, number> = {};');
  lines.push(
    `for (let expressionIndex = 0; expressionIndex < ${BENCHMARK_EXPRESSION_COUNT}; expressionIndex += 1) {`,
  );
  lines.push(
    `  for (let termIndex = 0; termIndex < ${BENCHMARK_TERMS_PER_EXPRESSION}; termIndex += 1) {`,
  );
  lines.push(
    '    const key = `v_${expressionIndex}_${termIndex}`; benchmarkModel[key] = expressionIndex + termIndex;',
  );
  lines.push('  }');
  lines.push('}');
  lines.push('');
  lines.push(
    'export const lightBenchmarkModel: Record<string, number> = { a: 1, b: 2 };',
  );
  lines.push('');
  lines.push(
    'export const benchmarkExpressionFactories: Array<() => IExpression> = [',
  );
  for (
    let expressionIndex = 0;
    expressionIndex < BENCHMARK_EXPRESSION_COUNT;
    expressionIndex += 1
  ) {
    lines.push(
      `  () => rsx(${JSON.stringify(buildExpressionString(expressionIndex))})(benchmarkModel),`,
    );
  }
  lines.push('];');
  lines.push('');
  lines.push(
    'export const lightBenchmarkExpressionFactories: Array<() => IExpression> = [',
  );
  for (
    let expressionIndex = 0;
    expressionIndex < BENCHMARK_EXPRESSION_COUNT;
    expressionIndex += 1
  ) {
    lines.push("  () => rsx('a + b')(lightBenchmarkModel),");
  }
  lines.push('];');
  lines.push('');

  await fs.mkdir(path.dirname(outputPath), { recursive: true });
  await fs.writeFile(outputPath, `${lines.join('\n')}\n`, 'utf8');

  console.info(
    `[rsx-next-example] generated static benchmark expressions: count=${BENCHMARK_EXPRESSION_COUNT}, terms=${BENCHMARK_TERMS_PER_EXPRESSION}`,
  );
}

run().catch((error) => {
  console.error(error instanceof Error ? error.message : String(error));
  process.exitCode = 1;
});
