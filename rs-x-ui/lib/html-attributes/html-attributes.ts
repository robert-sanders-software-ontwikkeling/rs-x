export function getHtmlAttributeInfo(
   tagName: string,
   attributeName
): IHtmlAttribute | undefined {
   if (globalHtmlAttributes[attributeName]) {
      return globalHtmlAttributes[attributeName];
   }

   const lowerCaseTagName = tagName.toLowerCase();
   if (elementAttributes[lowerCaseTagName]) {
      return elementAttributes[lowerCaseTagName][attributeName];
   }
   return undefined;
}
